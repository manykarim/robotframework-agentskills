def _style_files(key: str) -> list[Path]:
    return [SKILL_DIRS[key] / "SKILL.md", *references(key)]


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_verified_line_once(key):
    hits = [
        (p.name, ln)
        for p in _style_files(key)
        for ln in p.read_text(encoding="utf-8").splitlines()
        if "Verified against" in ln
    ]
    assert len(hits) == 1 and hits[0][0] == "SKILL.md", f"rf-{key}: 'Verified against' lines: {hits}"
    assert re.search(r"Verified against .+ \d+\.\d+(\.\d+)?, Robot Framework \d+\.\d+", hits[0][1]), hits[0][1]


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_no_shouting_in_prose(key):
    bad = []
    for path in _style_files(key):
        text = path.read_text(encoding="utf-8")
        if path.name == "SKILL.md":
            text = body_of(text)
        for no, line in prose_lines(text):
            words = set(re.findall(r"\b[A-Z][A-Z']+\b", line))
            loud = sorted(words & SHOUT_WORDS)
            if loud:
                bad.append(f"{path.name}:{no}: {loud}: {line.strip()[:80]}")
    assert not bad, f"rf-{key}: ALL-CAPS emphasis in prose:\n" + "\n".join(bad)


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_no_dated_statements(key):
    bad = []
    for path in _style_files(key):
        for no, line in prose_lines(path.read_text(encoding="utf-8")):
            if "Verified against" not in line and DATED_RE.search(line):
                bad.append(f"{path.name}:{no}: {line.strip()[:80]}")
    assert not bad, f"rf-{key}: time-sensitive statements:\n" + "\n".join(bad)


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_no_legacy_syntax(key):
    bad = []
    for path in _style_files(key):
        for block in robot_blocks(path.read_text(encoding="utf-8")):
            bad += [f"{path.name}: {ln.strip()}" for ln in block if LEGACY_RE.search(ln)]
    for ex in examples(key):
        bad += [f"{ex.name}: {ln.strip()}" for ln in ex.read_text(encoding="utf-8").splitlines() if LEGACY_RE.search(ln)]
    assert not bad, f"rf-{key}: legacy syntax:\n" + "\n".join(bad)


