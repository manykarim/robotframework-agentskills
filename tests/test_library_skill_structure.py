@pytest.mark.parametrize("key", KEY_PARAMS)
def test_reference_table_matches_files(key):
    body = section(skill_md(key), "When to read the references")
    rows = table_rows(body)
    assert rows and [c.lower() for c in rows[0][:2]] == ["read", "when"], f"rf-{key}: header {rows[:1]}"
