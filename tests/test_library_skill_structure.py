"""Structure, budget, reference and example rules for the five library skills.

Spec: openspec capability ``library-skill-structure`` (change
``restructure-library-skills``). Checks the canonical ``skills/rf-<key>/``
tree; the plugin and VS Code copies are generated by ``scripts/sync-skills.sh``
and compared by ``scripts/check-drift.sh`` (only the catalog-file absence is
checked here for every channel).

Keyword existence in fenced ```robotframework blocks, references and examples
is enforced by ``scripts/check-skill-keywords.py`` (``tests/test_skill_keywords.py``
runs it over the real tree); this module adds the same libdoc check for the
keywords named in the ``Which keyword for which situation`` table, which the
checker does not see because they are inline code in a Markdown table.
"""

from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
CHECKER_SCRIPT = ROOT / "scripts" / "check-skill-keywords.py"

# Skill key -> libdoc import name (also the module probed for the dry-run test).
LIBRARIES: dict[str, str] = {
    "browser": "Browser",
    "selenium": "SeleniumLibrary",
    "appium": "AppiumLibrary",
    "requests": "RequestsLibrary",
    "restinstance": "REST",
}
KEYS = list(LIBRARIES)
SKILL_DIRS = {k: ROOT / "skills" / f"rf-{k}" for k in KEYS}

# Skills not yet restructured: their cases are xfails (non-strict: some rules, such as the
# example dry run, already hold for the old content). Emptied as each skill is done.
PENDING: set[str] = set()


def _param(key: str, *values: object, id: str | None = None):
    marks = [pytest.mark.xfail(strict=False, reason=f"rf-{key} not restructured yet")] if key in PENDING else []
    return pytest.param(*(values or (key,)), id=id or key, marks=marks)


KEY_PARAMS = [_param(k) for k in KEYS]

# Script-based fallback skills named next to the robotcode commands (design D3).
LIBDOC_FALLBACK = "rf-libdoc"
RESULTS_FALLBACK = "rf-results"

REQUIRED_SECTIONS = [
    "Installation",
    "Import and defaults",
    "Which keyword for which situation",
    "Agent workflow",
    "Gotchas",
    "When to read the references",
    "Companion Skills",
]
# Optional sections may only sit between these two required ones.
OPTIONAL_AFTER, OPTIONAL_BEFORE = "Which keyword for which situation", "Gotchas"
# The trigger block (skill-triggering, tune-skill-descriptions D12) sits right
# after the orientation, before "Installation", within the first 20 body lines.
LEADING_SECTION = "When to use"

MAX_LINES = 250
MAX_CHARS = 12_000
MAX_ORIENTATION_LINES = 6  # ~5 lines of orientation + the "Verified against" line
TOC_WINDOW = 15
TOC_THRESHOLD = 100

SHOUT_WORDS = {
    "NEVER", "ALWAYS", "MUST", "CRITICAL", "IMPORTANT", "WARNING", "NOTE",
    "DO", "DON'T", "NOT", "SHOULD", "REQUIRED",
}
DATED_RE = re.compile(
    r"\bas of\b|\brecently\b|\bnew in\b|\bcurrently\b|"
    r"\b(January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{4}\b",
    re.I,
)
LEGACY_RE = re.compile(r"Run Keyword (?:If|Unless)(?=\s{2,}|\t|$)|\bExit For Loop\b|\[Return\]", re.I)
INSTALL_RE = re.compile(r"\bpip3? install\b|\buv add\b|\bnpm install\b|\bnpm i\b")
REF_LINK_RE = re.compile(r"references/([\w.-]+\.md)")
FENCE_RE = re.compile(r"^\s*```")
ROBOT_FENCE_RE = re.compile(r"^\s*```\s*(robotframework|robot)\s*$", re.I)

# Inline-code cells in the decision table that are settings or syntax, not keywords.
NOT_KEYWORDS = {
    "suite setup", "suite teardown", "test setup", "test teardown", "test template",
    "library", "resource", "variables", "test tags", "keyword tags",
}


# --- helpers ---------------------------------------------------------------


def skill_md(key: str) -> str:
    return (SKILL_DIRS[key] / "SKILL.md").read_text(encoding="utf-8")


def body_of(text: str) -> str:
    """SKILL.md without its YAML frontmatter."""
    if text.startswith("---"):
        end = text.find("\n---", 3)
        return text[end + 4:] if end != -1 else text
    return text


def h2_headings(text: str) -> list[str]:
    out, in_fence = [], False
    for line in text.splitlines():
        if FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if not in_fence and line.startswith("## "):
            out.append(line[3:].strip())
    return out


def section(text: str, heading: str) -> str:
    m = re.search(rf"^## {re.escape(heading)}[ \t]*\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    return m.group(1) if m else ""


def prose_lines(text: str) -> list[tuple[int, str]]:
    """(line number, line) outside fenced code, with inline code removed."""
    out, in_fence = [], False
    for no, line in enumerate(text.splitlines(), 1):
        if FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if not in_fence:
            out.append((no, re.sub(r"`[^`]*`", "", line)))
    return out


def robot_blocks(text: str) -> list[list[str]]:
    blocks, cur, inside = [], [], False
    for line in text.splitlines():
        if not inside and ROBOT_FENCE_RE.match(line):
            inside, cur = True, []
        elif inside and FENCE_RE.match(line):
            blocks.append(cur)
            inside = False
        elif inside:
            cur.append(line)
    return blocks


def fenced_blocks(text: str) -> list[list[str]]:
    blocks, cur, inside = [], [], False
    for line in text.splitlines():
        if FENCE_RE.match(line):
            if inside:
                blocks.append(cur)
            inside, cur = not inside, []
        elif inside:
            cur.append(line)
    return blocks


def table_rows(text: str) -> list[list[str]]:
    rows = []
    for line in text.splitlines():
        s = line.strip()
        if not s.startswith("|"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
            continue
        rows.append(cells)
    return rows


def references(key: str) -> list[Path]:
    ref_dir = SKILL_DIRS[key] / "references"
    return sorted(ref_dir.glob("*.md")) if ref_dir.is_dir() else []


def examples(key: str) -> list[Path]:
    ex_dir = SKILL_DIRS[key] / "assets" / "examples"
    return sorted(ex_dir.glob("*.robot")) if ex_dir.is_dir() else []


def slug(heading: str) -> str:
    s = re.sub(r"[^\w\s-]", "", heading.lower()).strip()
    return re.sub(r"\s+", "-", s)


def toc_problems(path: Path) -> list[str]:
    """A contents list must start within the first TOC_WINDOW lines and name every H2."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if len(lines) <= TOC_THRESHOLD:
        return []
    start = next(
        (i for i, ln in enumerate(lines[:TOC_WINDOW]) if re.match(r"\s*(?:[-*]|\d+\.)\s+", ln)), None
    )
    if start is None:
        return [f"{path.name}: {len(lines)} lines but no contents list in the first {TOC_WINDOW} lines"]
    end = start
    while end < len(lines) and re.match(r"\s*(?:[-*]|\d+\.)\s+", lines[end]):
        end += 1
    toc = "\n".join(lines[start:end]).lower()
    missing = [h for h in h2_headings("\n".join(lines)) if h.lower() not in toc and slug(h) not in toc]
    return [f"{path.name}: contents list misses H2 {h!r}" for h in missing]


def decision_table_keywords(text: str) -> list[str]:
    """Keyword-like inline-code spans in the ``Use`` column of the decision table."""
    names = []
    for row in table_rows(section(text, "Which keyword for which situation"))[1:]:
        if len(row) < 2:
            continue
        for span in re.findall(r"`([^`]+)`", row[1]):
            name = re.split(r"\s{2,}|\t", span.strip())[0].strip()
            if not re.fullmatch(r"[A-Z][A-Za-z0-9]*(?: [A-Za-z][A-Za-z0-9]*)+", name):
                continue
            if name.lower() in NOT_KEYWORDS:
                continue
            names.append(name)
    return names


def _load_checker():
    spec = importlib.util.spec_from_file_location("check_skill_keywords_structure", CHECKER_SCRIPT)
    module = importlib.util.module_from_spec(spec)
    sys.modules["check_skill_keywords_structure"] = module
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def keyword_problems(names: list[str], import_name: str) -> list[str]:
    """Names that are unknown or deprecated in the library + standard libraries."""
    pytest.importorskip("robot")
    checker = _load_checker()
    lib = checker.load_library(import_name)
    if lib is None:
        pytest.skip(f"{import_name} is not importable")
    std: dict[str, object] = {}
    for std_name in checker.STANDARD_LIBRARIES:
        info = checker.load_library(std_name)
        if info:
            std.update(info.keywords)
    probs = []
    for name in names:
        norm = checker.normalize(name)
        kw = lib.keywords.get(norm) or std.get(norm)
        if kw is None:
            probs.append(f"UNKNOWN {name}")
        elif kw.deprecated:
            probs.append(f"DEPRECATED {name}")
    return probs


# --- structure -------------------------------------------------------------


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_required_sections_in_order(key):
    heads = h2_headings(body_of(skill_md(key)))
    missing = [h for h in REQUIRED_SECTIONS if h not in heads]
    assert not missing, f"rf-{key}: missing sections {missing}"
    required_order = [h for h in heads if h in REQUIRED_SECTIONS]
    assert required_order == REQUIRED_SECTIONS, f"rf-{key}: section order {required_order}"
    lo, hi = heads.index(OPTIONAL_AFTER), heads.index(OPTIONAL_BEFORE)
    stray = [
        h for i, h in enumerate(heads)
        if h not in REQUIRED_SECTIONS and not lo < i < hi and not (i == 0 and h == LEADING_SECTION)
    ]
    assert not stray, f"rf-{key}: optional sections outside {OPTIONAL_AFTER!r}..{OPTIONAL_BEFORE!r}: {stray}"


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_orientation_is_short_and_has_version_line(key):
    body = body_of(skill_md(key))
    m = re.search(r"^# [^\n]*\n(.*?)(?=^## )", body, re.M | re.S)
    assert m, f"rf-{key}: no H1 title before the first section"
    lines = [ln for ln in m.group(1).splitlines() if ln.strip()]
    assert 1 <= len(lines) <= MAX_ORIENTATION_LINES, f"rf-{key}: orientation has {len(lines)} lines"
    assert any(ln.startswith("Verified against ") for ln in lines), f"rf-{key}: no 'Verified against' line"


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_size_budget(key):
    text = skill_md(key)
    n_lines, n_chars = len(text.splitlines()), len(text)
    assert n_lines <= MAX_LINES, f"rf-{key}: {n_lines} lines > {MAX_LINES}"
    assert n_chars <= MAX_CHARS, f"rf-{key}: {n_chars} chars > {MAX_CHARS}"


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_single_default_import(key):
    body = section(skill_md(key), "Import and defaults")
    assert body, f"rf-{key}: no 'Import and defaults' section"
    imports = [
        ln for block in fenced_blocks(body) for ln in block if re.match(r"^Library\s{2,}\S", ln.strip())
    ]
    assert len(imports) == 1, f"rf-{key}: expected one recommended Library import, got {imports}"
    assert re.match(rf"^Library\s{{2,}}{re.escape(LIBRARIES[key])}(\s|$)", imports[0].strip())
    assert robot_blocks(body), f"rf-{key}: no robotframework open/session example"
    assert "references/" in body, f"rf-{key}: escape hatch does not point to a reference file"


@pytest.mark.parametrize("key", KEY_PARAMS)
def test_install_commands_only_in_installation_section(key):
    text = body_of(skill_md(key))
    install = section(text, "Installation")
    assert "rf-setup" in install
    outside = text.replace(install, "")
    hits = [ln.strip() for ln in outside.splitlines() if INSTALL_RE.search(ln)]
    assert not hits, f"rf-{key}: install commands outside '## Installation': {hits}"


